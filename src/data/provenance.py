"""
Provenance Framework for Smart HVAC Control System.
Enforces explicit traceability of every measurement, derived feature,
calibrated parameter, external data source, and simulated assumption.
"""

from enum import Enum
from typing import Any, Dict, NamedTuple, Optional
import json


class ProvenanceType(str, Enum):
    """
    Provenance categories required for scientific and real-world deployment rigor.
    """
    OBSERVED = "OBSERVED"                      # Direct sensor reading from physical hardware (e.g., degC, RH%, kW)
    DERIVED = "DERIVED"                        # Mathematically computed from observed features (e.g., internal heat = plug + light)
    EXTERNAL = "EXTERNAL"                      # Sourced from validated external meteorological/grid databases
    FITTED = "FITTED"                          # Estimated using a documented fitting procedure
    FITTED_WITH_CAVEAT = "FITTED_WITH_CAVEAT"  # Statistically or physically identified from data subject to identifiable limits
    SIMULATED_ASSUMED = "SIMULATED_ASSUMED"    # Operational hypothesis or simulated scenario variable (e.g., window open state, synthetic weather)
    SIMULATED = "SIMULATED"                    # Dynamically generated by simulation / digital twin transitions


class ProvenanceRecord(NamedTuple):
    name: str
    provenance_type: ProvenanceType
    source: str
    unit: str
    description: str
    confidence: str  # "HIGH", "MEDIUM", "LOW"
    caveat: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "name": self.name,
            "provenance_type": self.provenance_type.value,
            "source": self.source,
            "unit": self.unit,
            "description": self.description,
            "confidence": self.confidence,
            "caveat": self.caveat
        }


