def get_provenance(name: str) -> ProvenanceRecord:
    """Retrieve provenance record for a given variable or parameter name."""
    if name in SYSTEM_PROVENANCE_REGISTRY:
        return SYSTEM_PROVENANCE_REGISTRY[name]
    return ProvenanceRecord(
        name=name,
        provenance_type=ProvenanceType.SIMULATED_ASSUMED,
        source="Unregistered parameter",
        unit="unknown",
        description="Default unregistered provenance",
        confidence="LOW"
    )


def export_provenance_table_md() -> str:
    """Export system provenance registry into formatted Markdown table."""
    lines = [
        "| Variable / Parameter | Type | Unit | Confidence | Source & Methodology | Caveat |",
        "| :--- | :---: | :---: | :---: | :--- | :--- |"
    ]
    for key, p in SYSTEM_PROVENANCE_REGISTRY.items():
        cav = p.caveat if p.caveat else "None"
        lines.append(f"| **{p.name}** (`{key}`) | `{p.provenance_type.value}` | `{p.unit}` | **{p.confidence}** | {p.source} | {cav} |")
    return "\n".join(lines)
